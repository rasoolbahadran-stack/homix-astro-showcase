export const productBySlug = (slug: string): Product | undefined =>
  products.find((p) => p.slug === slug);

export const productsByCategory = (categorySlug: string): Product[] =>
  products.filter((p) => p.categorySlug === categorySlug);

export const productsByBrand = (brandId: string): Product[] =>
  products.filter((p) => p.brandId === brandId);

export const bestSellers = (): Product[] =>
  [...products].sort((a, b) => b.soldCount - a.soldCount).slice(0, 8);

export const newArrivals = (): Product[] =>
  [...products]
    .sort((a, b) => +new Date(b.createdAt) - +new Date(a.createdAt))
    .slice(0, 8);

export const discountedProducts = (): Product[] =>
  products.filter((p) => p.oldPrice && p.oldPrice > p.price);

export const specialOffers = (): Product[] =>
  products.filter((p) => p.badge === 'special').slice(0, 8);

export const relatedProducts = (p: Product, n = 4): Product[] =>
  products
    .filter((x) => x.categorySlug === p.categorySlug && x.id !== p.id)
    .slice(0, n);

export function discountPercent(p: Product): number | null {
  if (!p.oldPrice || p.oldPrice <= p.price) return null;
  return Math.round((1 - p.price / p.oldPrice) * 100);
}
